NODE_STYLE = {
    "start": "rounded corners=7pt, draw=sfCm, fill=sfCm!10, text=sfInk",
    "proc":  "draw=sfKw, fill=sfKw!8, text=sfInk",
    "dec":   "diamond, aspect=2.1, draw=sfSt, fill=sfSt!10, text=sfInk, inner sep=2pt",
    "io":    "trapezium, trapezium left angle=68, trapezium right angle=112, "
             "draw=sfMute, fill=sfMute!12, text=sfInk",
}


def _flow(f: dict) -> str:
    vertical = f.get("dir", "vertical") == "vertical"
    step = "below=11mm of" if vertical else "right=13mm of"
    o = ["\\begin{center}",
         "\\begin{tikzpicture}[>={Stealth[length=5pt]}, thick, font=\\small,"
         " every node/.style={align=center}]"]
    prev = None
    for n in f.get("nodes", []):
        st = NODE_STYLE.get(n.get("type", "proc"), NODE_STYLE["proc"])
        pos = f"[{step} {prev}]" if prev else ""
        o.append(f"\\node[{st}, minimum height=8mm, inner xsep=6pt, "
                 f"text width={n.get('width','30mm')}] "
                 f"({n['id']}) {pos} {{{tx(n['text'])}}};")
        prev = n["id"]
    order = {n["id"]: i for i, n in enumerate(f.get("nodes", []))}
    for e in f.get("edges", []):
        lab_txt = tx(e["label"]) if e.get("label") else None
        lab = (f"node[font=\\scriptsize, fill=white, inner sep=2pt] {{{lab_txt}}}"
               if lab_txt else "")
        # A backward edge (loop-back) must route AROUND the column, never
        # straight through the intervening nodes.
        if order.get(e["to"], 0) < order.get(e["from"], 0):
            off = e.get("offset", 3.0)
            side, perp = ("west", f"-- ++(-{off},0)") if vertical else \
                         ("south", f"-- ++(0,-{off})")
            join = "|-" if vertical else "-|"
            o.append(f"\\draw[->] ({e['from']}.{side}) {perp} {lab} "
                     f"{join} ({e['to']}.{side});")
        else:
            bend = f"[bend {e['bend']}=28]" if e.get("bend") else ""
            o.append(f"\\draw[->] ({e['from']}) to{bend} {lab} ({e['to']});")
    o += ["\\end{tikzpicture}", "\\end{center}"]
    return "\n".join(o)


