def _plot(p: dict) -> str:
    o = ["\\begin{center}", "\\begin{tikzpicture}"]
    ax = [
        "width=0.86\\linewidth", "height=6.1cm",
        "axis lines=left", "axis line style={sfMute, -{Stealth[length=5pt]}}",
        "tick style={sfMute}", "label style={font=\\small}",
        "tick label style={font=\\footnotesize, color=sfMute}",
        "grid=both", "grid style={sfRule, very thin}",
        "legend style={font=\\footnotesize, draw=sfRule, fill=white}",
        "legend cell align=left",
        f"legend pos={p.get('legend_pos', 'north east')}",
        "clip mode=individual",
    ]
    for k, key in [("xlabel", "xlabel"), ("ylabel", "ylabel")]:
        if p.get(key):
            ax.append(f"{k}={{${p[key]}$}}")
    for k in ("xmin", "xmax", "ymin", "ymax"):
        if p.get(k) is not None:
            ax.append(f"{k}={p[k]}")
    o.append("\\begin{axis}[" + ", ".join(ax) + "]")

    for c in p.get("curves", []):
        st = CURVE_STYLE.get(c.get("style", "main"), CURVE_STYLE["main"])
        dom = c.get("domain", f'{p.get("xmin",-5)}:{p.get("xmax",5)}')
        keep = "" if c.get("legend") else ", forget plot"
        o.append(f"\\addplot[{st}, domain={dom}, samples=201, smooth{keep}] "
                 f"{{{c['expr']}}};")
        if c.get("legend"):
            o.append("\\addlegendentry{$" + c["legend"] + "$}")

    for pt in p.get("points", []):
        st = POINT_STYLE.get(pt.get("style", "step"), POINT_STYLE["step"])
        o.append(f"\\addplot[{st}, only marks, forget plot] "
                 f"coordinates {{({pt['x']},{pt['y']})}};")
        if pt.get("label"):
            pos = pt.get("anchor", "north west")
            o.append(f"\\node[anchor={pos}, font=\\scriptsize, text=sfInk, "
                     f"fill=white, fill opacity=0.82, text opacity=1, "
                     f"inner sep=2pt, xshift={pt.get('dx',0)}pt, "
                     f"yshift={pt.get('dy',0)}pt] "
                     f"at (axis cs:{pt['x']},{pt['y']}) {{{tx(pt['label'])}}};")

    for a in p.get("arrows", []):
        fx, fy = a["from"]
        tx_, ty = a["to"]
        o.append(f"\\draw[-{{Stealth[length=5pt]}}, thick, sfSt] "
                 f"(axis cs:{fx},{fy}) -- (axis cs:{tx_},{ty});")
        if a.get("label"):
            mx, my = (fx + tx_) / 2, (fy + ty) / 2
            o.append(f"\\node[font=\\scriptsize, sfSt, anchor=south west] "
                     f"at (axis cs:{mx},{my}) {{{tx(a['label'])}}};")

    o += ["\\end{axis}", "\\end{tikzpicture}", "\\end{center}"]
    return "\n".join(o)


