# ==========================================================================
# escaping
# ==========================================================================
# Latin Modern has no glyph for many technical symbols, and XeLaTeX drops a
# missing glyph SILENTLY — "nên đều ≥ 0" prints as "nên đều  0". Map them to
# real LaTeX macros so output never depends on font coverage.
UNI = {
    "≥": r"$\geq$", "≤": r"$\leq$", "≠": r"$\neq$", "≈": r"$\approx$",
    "≡": r"$\equiv$", "∼": r"$\sim$", "∝": r"$\propto$", "≪": r"$\ll$",
    "≫": r"$\gg$", "≜": r"$\triangleq$",
    "×": r"$\times$", "÷": r"$\div$", "±": r"$\pm$", "∓": r"$\mp$",
    "·": r"$\cdot$", "∘": r"$\circ$", "√": r"$\sqrt{\ }$", "⁄": "/",
    "→": r"$\rightarrow$", "←": r"$\leftarrow$", "↔": r"$\leftrightarrow$",
    "⇒": r"$\Rightarrow$", "⇐": r"$\Leftarrow$", "⇔": r"$\Leftrightarrow$",
    "↦": r"$\mapsto$", "⟶": r"$\longrightarrow$", "↑": r"$\uparrow$",
    "↓": r"$\downarrow$",
    "∈": r"$\in$", "∉": r"$\notin$", "⊂": r"$\subset$", "⊆": r"$\subseteq$",
    "∪": r"$\cup$", "∩": r"$\cap$", "∅": r"$\emptyset$", "∀": r"$\forall$",
    "∃": r"$\exists$", "¬": r"$\neg$", "∧": r"$\wedge$", "∨": r"$\vee$",
    "∞": r"$\infty$", "∂": r"$\partial$", "∇": r"$\nabla$", "∫": r"$\int$",
    "∑": r"$\sum$", "∏": r"$\prod$", "⊤": r"$\top$", "⊥": r"$\perp$",
    "‖": r"$\|$", "°": r"$^\circ$", "…": r"\ldots{}", "⋯": r"$\cdots$",
}
UNI.update({c: r"\textsuperscript{%s}" % d for c, d in
            zip("⁰¹²³⁴⁵⁶⁷⁸⁹", "0123456789")})
UNI.update({c: r"\textsubscript{%s}" % d for c, d in
            zip("₀₁₂₃₄₅₆₇₈₉", "0123456789")})
UNI.update({"⁻": r"\textsuperscript{$-$}", "⁺": r"\textsuperscript{$+$}",
            "ⁿ": r"\textsuperscript{n}", "ᵀ": r"\textsuperscript{T}",
            "ᵢ": r"\textsubscript{i}", "ⱼ": r"\textsubscript{j}",
            "ₙ": r"\textsubscript{n}", "ₖ": r"\textsubscript{k}",
            "⁻¹": r"\textsuperscript{$-1$}"})
UNI.update({c: "$\\%s$" % n for c, n in [
    ("α", "alpha"), ("β", "beta"), ("γ", "gamma"), ("δ", "delta"),
    ("ε", "epsilon"), ("ζ", "zeta"), ("η", "eta"), ("θ", "theta"),
    ("κ", "kappa"), ("λ", "lambda"), ("μ", "mu"), ("ν", "nu"), ("ξ", "xi"),
    ("ρ", "rho"), ("σ", "sigma"), ("τ", "tau"), ("φ", "phi"), ("χ", "chi"),
    ("ψ", "psi"), ("ω", "omega"), ("Γ", "Gamma"), ("Δ", "Delta"),
    ("Θ", "Theta"), ("Λ", "Lambda"), ("Σ", "Sigma"), ("Φ", "Phi"),
    ("Ψ", "Psi"), ("Ω", "Omega"), ("π", "pi"), ("Π", "Pi"),
]})


_UNI_ORDER = sorted(UNI, key=len, reverse=True)


def tx(s) -> str:
    """Escape a Vietnamese prose string for LaTeX text mode.

    Backslash is parked on a sentinel FIRST and restored LAST: its replacement
    `\\textbackslash{}` contains braces, and escaping those braces afterwards
    turned `\\theta` into the literal `\\{}theta` on the printed page.
    """
    s = str(s)
    BS = "\x00\x01BS\x01\x00"
    s = s.replace("\\", BS)
    for a, b in [("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
                 ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")]:
        s = s.replace(a, b)
    s = s.replace(BS, r"\textbackslash{}")
    if not s.isascii():                       # cheap guard: most strings skip this
        for a in _UNI_ORDER:                  # longest key first: "⁻¹" before "⁻"
            if a in s:
                s = s.replace(a, UNI[a])
    return s


def tt(s) -> str:
    """Escape for \\texttt{}. Never rewrite '-' into '\\-' (a discretionary
    hyphen renders as NOTHING, which silently eats minus signs in shape specs
    like 'y_hat - y')."""
    return r"\texttt{" + tx(s) + "}"


