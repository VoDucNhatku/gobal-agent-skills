def _tbl(colspec, head, rows) -> str:
    o = [r"\begin{tabular}{@{}" + colspec + r"@{}}", r"\toprule",
         " & ".join(r"\footnotesize\sffamily\bfseries " + h for h in head) + r"\\",
         r"\midrule"]
    o += [" & ".join(r) + r"\\" for r in rows]
    o += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(o)


def kind_of(c) -> str:
    """math | code | claim — decides the wording of every card-type-dependent
    label. Without this, a concept card gets told to 'xoá từng mảnh của công
    thức' when it has no formula at all."""
    if c.get("code"):
        return "code"
    if c.get("expr"):
        return "math"
    return "claim"


def _slot(key, inner, title=None, nobreak=False) -> str:
    t, hue = SLOT_TONE[key]
    env = "sfslotnb" if nobreak else "sfslot"
    return (f"\\begin{{{env}}}{{{title or t}}}{{slot{key}}}\n{inner}\n"
            f"\\end{{{env}}}")


def _chip(table, key, fallback="—"):
    lab = table.get(key, (fallback,))[0]
    return f"\\chip{{{key.replace('-', '')}}}{{{tx(lab)}}}"


def _chipdefs() -> list:
    """Colour + macro for every chip family used by the argument profile."""
    out = [r"\newcommand{\chip}[2]{\textcolor{white}{\colorbox{chip#1}"
           r"{\scriptsize\sffamily\bfseries\,#2\,}}}"]
    for tab in (EVIDENCE_KIND, CLAIM_STRENGTH, PROV_TAG, LOAD):
        for k, v in tab.items():
            out.append(f"\\definecolor{{chip{k.replace('-', '')}}}{{HTML}}{{{v[1]}}}")
    return out


